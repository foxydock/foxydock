const DOMAIN_REGEX = /^(?:[a-z0-9-]+\.)*([a-z]{2,})$/i;

/**
 * 简单遍历数组变量名，依次判断是否有效。
 * 如果都无效，则强制返回最后一个变量的值
 * @param {NginxHTTPRequest} r NGINX 请求对象
 * @param {string[]} varNames 变量数组
 * @returns 有效的变量的值
 */
function simpleJudgeVar(r, varNames) {
  let val;
  const arrLen = varNames.length;
  for (let i = 0; i < arrLen; i++) {
    const varName = varNames[i];
    val = r.variables[varName];
    if (val) {
      return val;
    }
  }

  // 默认强制返回最后一个元素
  return val;
}

/**
 * FoxyDockNginx 获取源头客户端 HTTP 请求的 URL 的 scheme 部分
 * @param {NginxHTTPRequest} r NGINX 请求对象
 * @returns 源头客户端请求协议
 */
function getFdnFirstClientUrlScheme(r) {
  // 优先尊重 X-Forwarded-Proto
  if (r.variables.http_x_forwarded_proto) {
    return r.variables.http_x_forwarded_proto;
  }

  if (r.variables.ssl_server_name) {
    return "https";
  }

  return simpleJudgeVar(r, ["http_x_forwarded_proto", "scheme"]);
}

